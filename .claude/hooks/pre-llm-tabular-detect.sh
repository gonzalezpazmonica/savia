#!/usr/bin/env bash
set -uo pipefail
# pre-llm-tabular-detect.sh — Capa 1: detect tabular data before LLM call
# If prompt contains >5 lines of tabular data, replace with statistical profile

INPUT=$(cat)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROFILER="$SCRIPT_DIR/../../scripts/tabular-profile.py"
SUMMARIZER="$SCRIPT_DIR/../../scripts/tabular-summarize.sh"

# SE-324: detect .xlsx file path references in the prompt and profile them
# directly (before the inline line-count gate).
XLSX_PATH=$(echo "$INPUT" | grep -oE '[A-Za-z0-9_./-]+\.xlsx' 2>/dev/null | head -1 || true)
if [[ -n "$XLSX_PATH" && -f "$XLSX_PATH" ]]; then
  PROFILE=$(python3 "$PROFILER" "$XLSX_PATH" 2>/dev/null || echo "")
  if [[ -n "$PROFILE" && "$PROFILE" != *'"error"'* ]]; then
    cat <<OUTPUT
$INPUT

[STATISTICAL PROFILE — generated by tabular-profile.py from $XLSX_PATH. Numbers are exact. LLM: interpret, do NOT recompute.]
$PROFILE
OUTPUT
    exit 0
  fi
fi

# Quick heuristic: count lines that look like CSV or markdown tables
CSV_LINES=$(echo "$INPUT" | grep -cE '^[^|]*,{1,}[^,].*[0-9]' 2>/dev/null || [ $? -eq 1 ] || echo 0)
MD_LINES=$(echo "$INPUT" | grep -cE '^\s*\|.+\|' 2>/dev/null || [ $? -eq 1 ] || echo 0)
TOTAL_TABULAR=$((CSV_LINES + MD_LINES))

if [[ "$TOTAL_TABULAR" -lt 5 ]]; then
  echo "$INPUT"
  exit 0
fi

# Extract tabular portion and profile it. Only the tabular lines go to the
# profiler: prose lines would be read as the CSV header and break profiling.
# Field count ignores commas inside double quotes. CSV rows = lines with the
# modal field count among data rows (those with a digit) that sit next to
# another line of that same count, plus the header just above a data row; so
# prose with a stray comma, or a lone sentence with the same count, is kept.
split_tabular() { # $1 = keep (tabular lines) | drop (everything else)
  printf '%s\n' "$INPUT" | awk -v mode="$1" '
    function fields(s,   n, i, ch, q) {
      n = 1; q = 0
      for (i = 1; i <= length(s); i++) {
        ch = substr(s, i, 1)
        if (ch == "\"") q = !q
        else if (ch == "," && !q) n++
      }
      return n
    }
    { line[NR] = $0 }
    /^[ \t]*\|.+\|/ { md[NR] = 1; next }
    /^[^|]*,+[^,].*[0-9]/ { f[NR] = fields($0); cnt[f[NR]]++; if (cnt[f[NR]] > best) { best = cnt[f[NR]]; mode_f = f[NR] } }
    END {
      for (i = 1; i <= NR; i++) if (!md[i] && !(i in f) && line[i] !~ /\|/ && line[i] ~ /,/) g[i] = fields(line[i])
      for (i = 1; i <= NR; i++) {
        t = 0
        if (md[i]) t = 1
        else if (best && line[i] !~ /\|/) {
          me = (i in f) ? f[i] : (i in g ? g[i] : -1)
          if (me == mode_f) {
            if ((i in f) && (((i-1) in f && f[i-1] == mode_f) || ((i+1) in f && f[i+1] == mode_f))) t = 1
            else if (!(i in f) && (i+1) in f && f[i+1] == mode_f) t = 1
            else if ((i in f) && ((i-1) in g && g[i-1] == mode_f)) t = 1
          }
        }
        if ((mode == "keep") == (t == 1)) print line[i]
      }
    }'
}
TABULAR_PART=$(split_tabular keep)
if [[ -x "$SUMMARIZER" ]]; then
  PROFILE=$(echo "$TABULAR_PART" | "$SUMMARIZER" - 2>/dev/null || echo "")
else
  PROFILE=$(echo "$TABULAR_PART" | python3 "$PROFILER" 2>/dev/null || echo "")
fi

if [[ -n "$PROFILE" && "$PROFILE" != *'"error"'* && "$PROFILE" != *'"detected":false'* ]]; then
  # Replace raw tabular data with profile in the prompt
  # Keep non-tabular parts of the original prompt
  NON_TABULAR=$(split_tabular drop)
  
  cat <<OUTPUT
$NON_TABULAR

[STATISTICAL PROFILE — generated by tabular-profile.py. Numbers are exact. LLM: interpret, do NOT recompute.]
$PROFILE
OUTPUT
else
  echo "$INPUT"
fi
